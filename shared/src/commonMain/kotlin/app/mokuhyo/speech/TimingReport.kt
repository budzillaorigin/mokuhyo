package app.mokuhyo.speech

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import kotlin.math.ceil
import kotlin.math.roundToLong

/**
 * A timing report (BRIEF_INTERVIEW_SPEED N1): what `--bench-interview` writes and what Settings → Speech & audio →
 * "Export timing report" saves. Timings, counts and identifiers only; no transcript text and no audio.
 */
@Serializable
data class TimingReport(
    val format: String = FORMAT,
    val generatedBy: String,
    val appVersion: String,
    val machine: Machine,
    /** Measured on real hardware with real models (bench / live session) or a dry run with stand-ins. */
    val real: Boolean,
    val sessions: List<Session>,
    val summary: Summary,
    /** Stages that could not run on this machine, with why (no model, no voice, no microphone…). */
    val notRun: Map<String, String> = emptyMap(),
    val cancellation: List<CancelSample> = emptyList(),
) {
    @Serializable
    data class Machine(val os: String, val arch: String, val cpuCores: Int, val ramGb: Double, val gpu: String? = null, val power: String? = null)

    @Serializable
    data class Mark(val stage: String, val ms: Long, val meaningful: Boolean = true)

    @Serializable
    data class Turn(
        val index: Int,
        val cold: Boolean = false,
        val answerMs: Long? = null,
        val fallback: String = FallbackKind.NONE.wire,
        val llmAttempts: Int = 0,
        val prerendered: Boolean = false,
        val ttsSynthMs: Long? = null,
        val ttsAudioMs: Long? = null,
        val peakRssMb: Long? = null,
        val events: List<Mark> = emptyList(),
        val stages: Map<String, Long> = emptyMap(),
    )

    @Serializable
    data class Session(
        val id: String,
        val kind: String,
        val language: String,
        val modelId: String? = null,
        val modelHash: String? = null,
        val voiceId: String? = null,
        val backend: String? = null,
        val llmThreads: Int? = null,
        val asrThreads: Int? = null,
        val ttsThreads: Int? = null,
        val warmupMs: Map<String, Long> = emptyMap(),
        val turns: List<Turn> = emptyList(),
    )

    /** One cancellation probe: which stage was stopped and how long until it actually stopped. */
    @Serializable
    data class CancelSample(val stage: String, val ms: Long)

    @Serializable
    data class Stat(val n: Int, val p50: Long, val p95: Long, val max: Long)

    @Serializable
    data class Summary(
        /** Warm turns only (turn 0 and cold turns are reported apart), per stage. */
        val warm: Map<String, Stat>,
        val cold: Map<String, Stat>,
        /** Per language and answer length bucket ("short" / "long"), the headline only. */
        val firstAudioBy: Map<String, Stat> = emptyMap(),
        val ttsRealTimeFactor: Double? = null,
        val fallbackRate: Double? = null,
        val prerenderedRate: Double? = null,
        val peakRssMb: Long? = null,
        val cancel: Map<String, Stat> = emptyMap(),
        val warmupMs: Map<String, Long> = emptyMap(),
    )

    fun toJson(): String = json.encodeToString(serializer(), this)

    /** A short Markdown table for an issue, the PR and PROGRESS. */
    fun toMarkdown(): String = buildString {
        appendLine("# Mokuhyo interview timing report")
        appendLine()
        appendLine("- Generated by: $generatedBy, app $appVersion")
        appendLine("- Machine: ${machine.os} ${machine.arch}, ${machine.cpuCores} cores, ${machine.ramGb} GB RAM" +
            (machine.gpu?.let { ", $it" } ?: "") + (machine.power?.let { ", $it" } ?: ""))
        sessions.map { listOfNotNull(it.modelId, it.backend, it.voiceId).joinToString(" · ") }.distinct().filter { it.isNotBlank() }
            .forEach { appendLine("- Setup: $it") }
        appendLine("- Real hardware and models: ${if (real) "yes" else "NO — dry run, not a latency measurement"}")
        appendLine()
        appendLine("| Stage (warm turns) | n | p50 ms | p95 ms | max ms |")
        appendLine("| --- | ---: | ---: | ---: | ---: |")
        summary.warm.forEach { (k, s) -> appendLine("| $k | ${s.n} | ${s.p50} | ${s.p95} | ${s.max} |") }
        if (summary.cold.isNotEmpty()) {
            appendLine()
            appendLine("| Stage (cold / first turn) | n | p50 ms | p95 ms | max ms |")
            appendLine("| --- | ---: | ---: | ---: | ---: |")
            summary.cold.forEach { (k, s) -> appendLine("| $k | ${s.n} | ${s.p50} | ${s.p95} | ${s.max} |") }
        }
        if (summary.firstAudioBy.isNotEmpty()) {
            appendLine()
            appendLine("| First meaningful audio by language / answer length | n | p50 ms | p95 ms |")
            appendLine("| --- | ---: | ---: | ---: |")
            summary.firstAudioBy.forEach { (k, s) -> appendLine("| $k | ${s.n} | ${s.p50} | ${s.p95} |") }
        }
        appendLine()
        appendLine("- TTS real-time factor: ${summary.ttsRealTimeFactor?.let { fmt(it) } ?: "not measured"}")
        appendLine("- Fallback rate: ${summary.fallbackRate?.let { pct(it) } ?: "n/a"}; prerendered prompts: ${summary.prerenderedRate?.let { pct(it) } ?: "n/a"}")
        appendLine("- Peak memory: ${summary.peakRssMb?.let { "$it MB (app process; Piper runs in its own process)" } ?: "not measured"}")
        summary.cancel.forEach { (k, s) -> appendLine("- Cancel $k: p50 ${s.p50} ms, p95 ${s.p95} ms (n=${s.n})") }
        summary.warmupMs.forEach { (k, v) -> appendLine("- Warm-up $k: $v ms (not counted as answer time)") }
        if (notRun.isNotEmpty()) {
            appendLine()
            appendLine("Not run on this machine:")
            notRun.forEach { (k, v) -> appendLine("- $k: $v") }
        }
    }

    companion object {
        const val FORMAT = "mokuhyo-timing/1"

        private val json = Json { prettyPrint = true; encodeDefaults = true; ignoreUnknownKeys = true }

        fun parse(text: String): TimingReport = json.decodeFromString(serializer(), text)

        /** Nearest-rank percentile ([p] in 0..100) of [values]; 0 for none. */
        fun percentile(values: List<Long>, p: Double): Long {
            if (values.isEmpty()) return 0
            val sorted = values.sorted()
            val rank = ceil(p / 100.0 * sorted.size).toInt().coerceIn(1, sorted.size)
            return sorted[rank - 1]
        }

        fun stat(values: List<Long>): Stat = Stat(values.size, percentile(values, 50.0), percentile(values, 95.0), values.maxOrNull() ?: 0)

        /**
         * Summary over [sessions]. Turn 0 and turns marked cold are "cold"; everything else is warm. [lengthOf] buckets a
         * turn's answer ("short" / "long"); by default answers of 30 s or more are long.
         */
        fun summarize(
            sessions: List<Session>,
            cancellation: List<CancelSample> = emptyList(),
            lengthOf: (Turn) -> String? = { t -> t.answerMs?.let { if (it >= LONG_ANSWER_MS) "long" else "short" } },
        ): Summary {
            val all = sessions.flatMap { s -> s.turns.map { s to it } }
            fun group(turns: List<Turn>): Map<String, Stat> {
                val keys = turns.flatMap { it.stages.keys }.distinct().sortedBy { STAGE_ORDER.indexOf(it).let { i -> if (i < 0) Int.MAX_VALUE else i } }
                return keys.associateWith { k -> stat(turns.mapNotNull { it.stages[k] }) }
            }
            val (cold, warm) = all.map { it.second }.partition { it.cold || it.index == 0 }
            val by = all.filter { (_, t) -> !(t.cold || t.index == 0) && t.stages[TurnTimeline.FIRST_AUDIO] != null }
                .groupBy { (s, t) -> s.language + " / " + (lengthOf(t) ?: "unknown") }
                .entries.sortedBy { it.key }
                .associate { (k, v) -> k to stat(v.map { it.second.stages.getValue(TurnTimeline.FIRST_AUDIO) }) }
            val synth = all.sumOf { it.second.ttsSynthMs ?: 0 }
            val audio = all.sumOf { it.second.ttsAudioMs ?: 0 }
            val partnerTurns = all.map { it.second }
            return Summary(
                warm = group(warm),
                cold = group(cold),
                firstAudioBy = by,
                ttsRealTimeFactor = if (audio > 0) round3(synth.toDouble() / audio) else null,
                fallbackRate = partnerTurns.takeIf { it.isNotEmpty() }?.let { ts -> round3(ts.count { it.fallback != FallbackKind.NONE.wire }.toDouble() / ts.size) },
                prerenderedRate = partnerTurns.takeIf { it.isNotEmpty() }?.let { ts -> round3(ts.count { it.prerendered }.toDouble() / ts.size) },
                peakRssMb = all.mapNotNull { it.second.peakRssMb }.maxOrNull(),
                cancel = cancellation.groupBy { it.stage }.mapValues { (_, v) -> stat(v.map { it.ms }) },
                warmupMs = sessions.flatMap { it.warmupMs.entries }.groupBy { it.key }.mapValues { (_, v) -> v.maxOf { it.value } },
            )
        }

        /** Answers at least this long are "long" (the brief's two-minute answers); shorter ones are "short". */
        const val LONG_ANSWER_MS = 30_000L

        val STAGE_ORDER = listOf(TurnTimeline.FIRST_AUDIO, "endpoint", "asr_queue", "asr", "llm_queue", "llm_first_token", "llm_validated",
            "tts_first_pcm", "output_open", "playback", "cancel")

        private fun round3(d: Double) = (d * 1000).roundToLong() / 1000.0
        private fun fmt(d: Double) = round3(d).toString()
        private fun pct(d: Double) = "${(d * 1000).roundToLong() / 10.0} %"
    }
}
