"""JLPT item bank pipeline (BRIEF §5.11): rule-based generation, validation, and LLM drafting.

Commands (run from tools/):
  uv run python items/gen_jlpt.py generate --packs ../content/packs --out items/bank/jlpt_generated.json
  uv run python items/gen_jlpt.py validate items/bank/jlpt_generated.json items/bank/jlpt_authored.json
  uv run python items/gen_jlpt.py draft --endpoint http://localhost:11434/v1 --model qwen3:8b \
      --level N3 --type paraphrase --count 10 --out items/bank/drafts/n3-paraphrase.json

Bank format: docs/CONTENT_PACKS.md "Exam item banks". Blueprint: items/jlpt_blueprints.json.

`generate` is deterministic for a given set of packs (no randomness beyond seeded shuffles keyed by item id) and
builds only what data supports honestly, all with source="generated":
  kanji_reading      Tatoeba sentence, target word underlined; choices are its reading + 3 wrong readings
                     (other on/kun readings of its kanji, voicing / long vowel / っ variants), none of which JMdict
                     lists as a reading of the written form.
  orthography        Same, reversed: the word in kana underlined; choices are written forms, distractors swap one
                     kanji for a same-reading or look-alike kanji and are not JMdict spellings of that reading.
  context            Tatoeba sentence with the word blanked; distractors are same-level, same-POS words inflected
                     like the key, rejected when Tatoeba attests them with the same neighbour or they share a
                     gloss with the key.
  grammar_form       grammar.sqlite Tatoeba example with the construction blanked; distractors are other points'
                     constructions (related points first, then the same level), minus near-synonyms and
                     attested fits. Level-agnostic: every level present in grammar.sqlite is generated.
  sentence_assembly  ★ format from a grammar example split into bunsetsu (tokenizer.sqlite).

Markup used in stems (the app renders these; same convention in the authored bank):
  <u>…</u>     underlined target (kanji_reading, orthography, paraphrase; also reading passages)
  （　　）     blank to fill (context, grammar_form, word_formation): U+FF08, two U+3000, U+FF09
  ＿＿＿        a sentence_assembly slot (three U+FF3F); ＿★＿ the starred slot. Slots are separated by U+3000,
               e.g. "彼は　＿＿＿　＿＿＿　＿★＿　＿＿＿　です。"; the answer is the chunk for ＿★＿.
  ［1］…       numbered blanks in a text_grammar passage body; the item's stem is the marker itself.
  | a | b |    table rows in info_retrieval passage bodies (first row is the header).
refs: "g:<grammar id>", "v:<JMdict id>", and "t:<Tatoeba sentence id>" for attribution of the source sentence.
"""

