@dataclass
class Report:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    counts: Counter = field(default_factory=Counter)  # (level, type) -> items
    vocab_warnings: Counter = field(default_factory=Counter)  # (level, type) -> items with above-level words


def _strings(obj):
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from _strings(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _strings(v)


def load_form_level(dictionary: Path) -> dict[str, int]:
    """Written form (containing kanji) -> easiest JLPT level of any JMdict entry spelled that way."""
    con = sqlite3.connect(f"file:{dictionary}?mode=ro", uri=True)
    fl: dict[str, int] = {}
    for text, jlpt in con.execute(
        "SELECT k.text, e.jlpt FROM entry_kanji k JOIN entry e ON e.id = k.entry_id WHERE e.jlpt IS NOT NULL"
    ):
        if has_kanji(text):
            fl[text] = max(fl.get(text, 0), jlpt)
    con.close()
    return fl


def above_level_words(text: str, level: int, form_level: dict[str, int], lattice=None) -> list[str]:
    """Kanji-containing words whose easiest JLPT level is above `level`. With the tokenizer pack, the dictionary
    (base) form of each content word is checked, so inflected verbs match (会っ → 会う); without it, a simple
    longest match over the text."""
    text = strip_markup(text)
    if lattice is not None:
        out = []
        for t in lattice.tokenize(text):
            # suffixes (室, 的), pronouns (彼) and lone kanji (時, 日) are too ambiguous to flag usefully
            if (t.pos1 not in {"名詞", "動詞", "形容詞", "副詞"} or len(t.base) < 2
                    or t.pos2 in {"固有名詞", "数", "接尾", "代名詞", "非自立"}):
                continue
            lv = form_level.get(t.base)
            if lv is not None and lv < level and has_kanji(t.base):
                out.append(f"{t.base}(N{lv})")
        return out
    out = []
    i = 0
    while i < len(text):
        hit = None
        for n in range(min(8, len(text) - i), 0, -1):
            sub = text[i:i + n]
            if has_kanji(sub) and sub in form_level:
                hit = sub
                break
        if hit:
            if form_level[hit] < level:
                out.append(f"{hit}(N{form_level[hit]})")
            i += len(hit)
        else:
            i += 1
    return out


def validate_banks(banks: list[tuple[str, dict]], blueprint: dict[str, dict[str, int]],
                   form_level: dict[str, int] | None = None, lattice=None) -> Report:
    rep = Report()
    passage_ids: dict[str, dict] = {}
    item_ids: set[str] = set()
    stems: dict[tuple, str] = {}
    for name, bank in banks:
        err = rep.errors.append
        for k in ("bank", "title", "license", "attribution"):
            if not isinstance(bank.get(k), str) or not bank.get(k):
                err(f"{name}: missing or empty '{k}'")
        if not isinstance(bank.get("items"), list):
            err(f"{name}: 'items' must be a list")
            continue
        if not isinstance(bank.get("passages", []), list):
            err(f"{name}: 'passages' must be a list")
            continue
        for s in _strings(bank):
            if not unicodedata.is_normalized("NFC", s):
                err(f"{name}: text not NFC: {s[:30]!r}")
        for ps in bank.get("passages", []):
            pid = ps.get("id")
            where = f"{name}: passage {pid}"
            if not isinstance(pid, str) or not pid:
                err(f"{name}: passage without id")
                continue
            if pid in passage_ids:
                err(f"{where}: duplicate passage id")
            passage_ids[pid] = ps
            _check_common(ps, where, err, blueprint, passage=True)
            if not isinstance(ps.get("body"), str):
                err(f"{where}: body must be a string")
            if "script" in ps:
                _check_script(ps["script"], where, err)
            if not (ps.get("body") or ps.get("script")):
                err(f"{where}: needs a body or a script")
            for k in ("textType", "title"):
                if not isinstance(ps.get(k), str) or not ps.get(k):
                    err(f"{where}: missing '{k}'")
            _check_markup(ps.get("body", ""), where, err)
        for it in bank["items"]:
            iid = it.get("id")
            where = f"{name}: item {iid}"
            if not isinstance(iid, str) or not iid:
                err(f"{name}: item without id")
                continue
            if iid in item_ids:
                err(f"{where}: duplicate item id")
            item_ids.add(iid)
            _check_common(it, where, err, blueprint, passage=False)
            typ, level = it.get("type"), it.get("level")
            stem, choices, answer = it.get("stem"), it.get("choices"), it.get("answer")
            if not isinstance(stem, str) or (not stem and not it.get("script")):
                err(f"{where}: stem must be a non-empty string")
                stem = ""
            want = 3 if typ in THREE_CHOICE_TYPES else 4
            if not isinstance(choices, list) or not all(isinstance(c, str) and c.strip() for c in choices):
                err(f"{where}: choices must be non-empty strings")
                choices = []
            elif it.get("exam") == "JLPT" and len(choices) != want:
                err(f"{where}: {typ} needs {want} choices, has {len(choices)}")
            elif it.get("exam") != "JLPT" and len(choices) != 4:
                err(f"{where}: needs 4 choices")
            if len(set(choices)) != len(choices):
                err(f"{where}: choices not distinct")
            if not isinstance(answer, int) or isinstance(answer, bool) or not (0 <= answer < max(len(choices), 1)):
                err(f"{where}: answer {answer!r} out of range")
            if not isinstance(it.get("explanation"), str) or not it.get("explanation", "").strip():
                err(f"{where}: missing explanation")
            refs = it.get("refs", [])
            if not isinstance(refs, list) or not all(isinstance(r, str) and re.match(r"^[a-z]+:.+", r) for r in refs):
                err(f"{where}: refs must be strings like 'g:<id>' / 'v:<id>'")
            if "script" in it:
                _check_script(it["script"], where, err)
            _check_markup(stem, where, err)
            pid = it.get("passageId")
            if pid is not None and not isinstance(pid, str):
                err(f"{where}: passageId must be a string")
            script_text = "|".join(x.get("text", "") for x in it.get("script", []) if isinstance(x, dict))
            key = stem_key(typ, pid or "", stem, script_text, choices)
            if key in stems:
                err(f"{where}: duplicate stem (same as {stems[key]})")
            stems[key] = iid
            if it.get("exam") == "JLPT" and level in blueprint:
                rep.counts[(level, typ)] += 1
                if typ == "sentence_assembly" and (stem.count(STAR) != 1 or stem.count(SLOT) != 3):
                    err(f"{where}: sentence_assembly stem needs 3 {SLOT} slots and one {STAR}")
                if typ in {"kanji_reading", "orthography", "paraphrase"} and stem.count(U_OPEN) != 1:
                    err(f"{where}: {typ} stem needs exactly one <u>…</u>")
                if typ in {"context", "grammar_form", "word_formation"} and BLANK not in stem:
                    err(f"{where}: {typ} stem needs the blank {BLANK}")
                if form_level is not None:
                    # kanji_reading/orthography distractors are non-words by design: check the stem only
                    texts = [stem] if typ in {"kanji_reading", "orthography"} else [stem, *choices]
                    if typ == "quick_response":  # the stem is the fixed instruction; the prompt is the script
                        texts = [x.get("text", "") for x in it.get("script", []) if isinstance(x, dict)] + choices
                    hard = sorted({w for t in texts for w in above_level_words(t, level_num(level), form_level, lattice)})
                    if hard:
                        rep.vocab_warnings[(level, typ)] += 1
                        rep.warnings.append(f"{where}: above-level words {', '.join(hard[:5])}")
    # cross-file passage checks
    for name, bank in banks:
        for it in bank.get("items", []):
            pid = it.get("passageId")
            if pid is None:
                continue
            ps = passage_ids.get(pid)
            where = f"{name}: item {it.get('id')}"
            if ps is None:
                rep.errors.append(f"{where}: passageId {pid} not found")
                continue
            if ps.get("level") != it.get("level") or ps.get("exam") != it.get("exam"):
                rep.errors.append(f"{where}: level/exam differs from passage {pid}")
            if it.get("type") == "text_grammar":
                m = TG_MARK.fullmatch(it.get("stem", ""))
                if not m or it["stem"] not in ps.get("body", ""):
                    rep.errors.append(f"{where}: text_grammar stem must be a ［n］ marker present in the passage")
            if form_level is not None and it.get("exam") == "JLPT" and it.get("level") in blueprint:
                body = ps.get("body", "") + "".join(x.get("text", "") for x in ps.get("script", []))
                hard = sorted(set(above_level_words(body, level_num(it["level"]), form_level, lattice)))
                if hard and not ps.get("_warned"):
                    ps["_warned"] = True
                    rep.warnings.append(f"{name}: passage {pid}: above-level words {', '.join(hard[:6])}")
    for ps in passage_ids.values():
        ps.pop("_warned", None)
    used = {it.get("passageId") for _, b in banks for it in b.get("items", [])}
    for pid in passage_ids:
        if pid not in used:
            rep.warnings.append(f"passage {pid} has no items")
    return rep


def _check_common(obj: dict, where: str, err, blueprint: dict[str, dict[str, int]], passage: bool) -> None:
    exam, level = obj.get("exam"), obj.get("level")
    if exam not in EXAMS:
        err(f"{where}: exam must be one of {sorted(EXAMS)}")
    if exam == "JLPT":
        if level not in LEVELS:
            err(f"{where}: JLPT level must be N5..N1, got {level!r}")
        elif not passage and obj.get("type") not in blueprint.get(level, {}):
            err(f"{where}: type {obj.get('type')!r} is not in the {level} blueprint")
    elif not isinstance(level, str) or not level:
        err(f"{where}: missing level")
    if not isinstance(obj.get("source"), str) or not obj.get("source"):
        err(f"{where}: missing source")
    if not isinstance(obj.get("verified"), bool):
        err(f"{where}: verified must be true/false")
    if obj.get("source") == "llm" and obj.get("verified") is not False:
        err(f"{where}: source=llm items must stay verified=false until review")


def _check_script(script, where: str, err) -> None:
    if not isinstance(script, list) or not script:
        err(f"{where}: script must be a non-empty list")
        return
    for line in script:
        if not isinstance(line, dict) or not isinstance(line.get("text"), str) or not line.get("text"):
            err(f"{where}: script lines need text")
        elif line.get("voice") not in VOICES or not isinstance(line.get("speaker"), str):
            err(f"{where}: script line needs speaker and voice in {sorted(VOICES)}")


def _check_markup(text: str, where: str, err) -> None:
    if text.count(U_OPEN) != text.count(U_CLOSE) or re.search(r"<u>[^<]*<u>", text):
        err(f"{where}: unbalanced <u>…</u>")
    if re.search(r"<(?!/?u>)[a-zA-Z/][^>]*>", text):
        err(f"{where}: only <u> markup is allowed")


def coverage_table(rep: Report, blueprint: dict[str, dict[str, int]]) -> tuple[str, list[str]]:
    types = []
    for lv in LEVELS:
        for t in blueprint.get(lv, {}):
            if t not in types:
                types.append(t)
    titles = type_titles() if BLUEPRINTS.exists() else {}
    lines = [f"{'type':<22}" + "".join(f"{lv:>12}" for lv in LEVELS)]
    short: list[str] = []
    for t in types:
        row = f"{t:<22}"
        for lv in LEVELS:
            need = blueprint.get(lv, {}).get(t)
            if need is None:
                row += f"{'-':>12}"
                continue
            have = rep.counts[(lv, t)]
            mark = "" if have >= need else " !"
            row += f"{f'{have}/{need}{mark}':>12}"
            if have < need:
                short.append(f"{lv} {t} ({titles.get(t, t)}): {have}/{need}")
        lines.append(row)
    return "\n".join(lines), short


