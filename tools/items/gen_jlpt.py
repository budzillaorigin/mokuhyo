# --- text helpers -------------------------------------------------------------------------------------------


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s)


def hira(s: str) -> str:
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)


def is_kanji(c: str) -> bool:
    o = ord(c)
    return 0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF or 0x20000 <= o <= 0x2FFFF or c in "々〆"


def is_hira(c: str) -> bool:
    return "ぁ" <= c <= "ゖ" or c == "ー"


def is_kana(c: str) -> bool:
    return is_hira(c) or "ァ" <= c <= "ヺ"


def has_kanji(s: str) -> bool:
    return any(is_kanji(c) for c in s)


def strip_markup(s: str) -> str:
    return s.replace(U_OPEN, "").replace(U_CLOSE, "")


def level_num(level: str) -> int:
    return int(level[1])


def seeded(key: str) -> random.Random:
    return random.Random(key)  # str seeds are hashed with SHA-512: stable across runs and platforms


VOICE = dict(zip("かきくけこさしすせそたちつてとはひふへほ", "がぎぐげござじずぜぞだぢづでどばびぶべぼ"))
UNVOICE = {v: k for k, v in VOICE.items()} | dict(zip("ぱぴぷぺぽ", "はひふへほ"))
HALF = dict(zip("はひふへほ", "ぱぴぷぺぽ"))
O_ROW = set("おこごそぞとどのほぼぽもよろょ")
E_ROW = set("えけげせぜてでねへべぺめれ")
SOKUON_OK = set("かきくけこさしすせそたちつてとぱぴぷぺぽ")


def reading_variants(segs: list[str]) -> list[str]:
    """Plausible misreadings of a reading split into per-kanji segments: voicing / handakuten at a segment start,
    long vowel added or dropped at a segment end, っ at a segment boundary, big ゃゅょ. The kind of confusion
    learners actually make (けいざい/げいざい, しょうねん/しょねん, がっこう/がくこう)."""
    out: list[str] = []

    def emit(i: int, seg: str) -> None:
        out.append("".join(seg if j == i else x for j, x in enumerate(segs)))

    for i, seg in enumerate(segs):
        if not seg:
            continue
        c = seg[0]
        if c in VOICE:
            emit(i, VOICE[c] + seg[1:])
        if c in UNVOICE:
            emit(i, UNVOICE[c] + seg[1:])
        if c in HALF and i > 0:
            emit(i, HALF[c] + seg[1:])
        last = seg[-1]
        long_u = last == "う" and (seg[-2:-1] in O_ROW or seg[-2:-1] == "ゅ")
        long_i = last == "い" and seg[-2:-1] in E_ROW
        if len(seg) >= 2 and (long_u or long_i):
            emit(i, seg[:-1])
        elif last in O_ROW or last == "ゅ":
            emit(i, seg + "う")
        elif last in E_ROW:
            emit(i, seg + "い")
        nxt = segs[i + 1] if i + 1 < len(segs) else ""
        if nxt and nxt[0] in SOKUON_OK and len(seg) >= 2 and last in "つくちき":
            emit(i, seg[:-1] + "っ")
        if last == "っ":
            emit(i, seg[:-1] + "つ")
            emit(i, seg[:-1] + "く")
        for k, ch in enumerate(seg):
            if ch in "ゃゅょ":
                emit(i, seg[:k] + {"ゃ": "や", "ゅ": "ゆ", "ょ": "よ"}[ch] + seg[k + 1:])
    r = "".join(segs)
    seen, res = {r}, []
    for v in out:
        if v not in seen and v and v[0] not in "っんー" and not is_small(v[0]):
            seen.add(v)
            res.append(v)
    return res


GOJUON = ["あいうえお", "かきくけこ", "がぎぐげご", "さしすせそ", "ざじずぜぞ", "たちつてと", "だぢづでど",
          "なにぬねの", "はひふへほ", "ばびぶべぼ", "ぱぴぷぺぽ", "まみむめも", "らりるれろ"]
ROW_OF = {c: row for row in GOJUON for c in row}


def vowel_shifts(r: str) -> list[str]:
    """Readings one vowel away (ほん→はん, ひと→ふと): the fallback pool when a word has few other readings."""
    out = []
    for i, c in enumerate(r):
        if c in ROW_OF and not (i + 1 < len(r) and is_small(r[i + 1])):
            out += [r[:i] + x + r[i + 1:] for x in ROW_OF[c] if x != c]
    return out


def is_small(c: str) -> bool:
    return c in "ぁぃぅぇぉゃゅょゎっ"


def split_tail(surface: str, reading: str) -> tuple[str, str, str, str] | None:
    """Split a written span and its hiragana reading into (kana head, kanji core, its reading, kana tail),
    e.g. ("起きます", "おきます") -> ("", "起", "お", "きます"); ("お茶", "おちゃ") -> ("お", "茶", "ちゃ", "")."""
    h = 0
    while h < len(surface) and h < len(reading) and not is_kanji(surface[h]) and surface[h] == reading[h]:
        h += 1
    t = 0
    while (t < len(surface) - h and t < len(reading) - h and not is_kanji(surface[-1 - t])
           and surface[-1 - t] == reading[-1 - t]):
        t += 1
    core, core_r = surface[h:len(surface) - t], reading[h:len(reading) - t]
    if not core or not core_r or not all(is_kanji(c) or c in "ヶ" for c in core):
        return None
    return surface[:h], core, core_r, surface[len(surface) - t:]


# --- blueprint ----------------------------------------------------------------------------------------------


def load_blueprint(path: Path = BLUEPRINTS) -> dict[str, dict[str, int]]:
    """level ("N5".."N1") -> {item type: count in one full mock}."""
    data = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, dict[str, int]] = {}
    for lv in data["levels"]:
        types: dict[str, int] = {}
        for sec in lv["sections"]:
            for it in sec["items"]:
                types[it["type"]] = types.get(it["type"], 0) + it["count"]
        out[f"N{lv['level']}"] = types
    return out


def type_titles(path: Path = BLUEPRINTS) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {it["type"]: it["title"] for lv in data["levels"] for s in lv["sections"] for it in s["items"]}


