def draft(endpoint: str, model: str, level: str, typ: str, count: int, api_key: str | None,
          blueprint: dict[str, dict[str, int]], timeout: int = 600) -> dict:
    if level not in blueprint or typ not in blueprint[level]:
        raise SystemExit(f"{typ} is not in the {level} blueprint")
    if typ not in TYPE_GUIDE:
        raise SystemExit(f"draft supports {sorted(TYPE_GUIDE)}; passage-based types are authored by hand for now")
    n = 3 if typ in THREE_CHOICE_TYPES else 4
    system = (
        "You write ORIGINAL Japanese-language test items in the style of the JLPT. Never copy or paraphrase official "
        "JLPT items or prep books. Japanese must be natural, NFC, and at or below the requested level. Exactly one "
        "answer is correct and unambiguous. Explanations are in English. Reply with JSON only."
    )
    user = (
        f"Write {count} items. Level: {level}. Type: {typ}. {TYPE_GUIDE[typ]}\n"
        f"Each item has {n} distinct choices. Spread the correct answer position evenly.\n"
        'Reply as {"items": [{"stem": "...", "choices": [...], "answer": <0-based index>, '
        '"explanation": "<English>"' + (', "script": [...]' if typ == "quick_response" else "") + "}]}"
    )
    url = endpoint.rstrip("/")
    if not url.endswith("/chat/completions"):
        url += "/chat/completions" if url.endswith("/v1") else "/v1/chat/completions"
    body = json.dumps({
        "model": model, "temperature": 0.7, "response_format": {"type": "json_object"},
        "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
    }).encode()
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    req = urllib.request.Request(url, data=body, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        content = json.load(resp)["choices"][0]["message"]["content"]
    return normalize_draft(json.loads(content), level, typ, stamp=time.strftime("%Y%m%d%H%M%S"))


def normalize_draft(data: dict, level: str, typ: str, stamp: str) -> dict:
    """Turn a model's {"items": [...]} into a bank, labeled source=llm / verified=false."""
    items = []
    for i, raw in enumerate(data.get("items", []), 1):
        it = {
            "id": f"jld-{level.lower()}-{typ}-{stamp}-{i:02d}", "exam": "JLPT", "level": level, "type": typ,
            "stem": nfc(str(raw.get("stem", ""))), "choices": [nfc(str(c)) for c in raw.get("choices", [])],
            "answer": raw.get("answer"), "explanation": nfc(str(raw.get("explanation", ""))),
            "refs": [], "source": "llm", "verified": False,
        }
        if raw.get("script"):
            it["script"] = [
                {"speaker": nfc(str(x.get("speaker", "A"))), "voice": x.get("voice", "female"),
                 "text": nfc(str(x.get("text", "")))} for x in raw["script"] if isinstance(x, dict)
            ]
        items.append(it)
    return {
        "bank": f"jlpt-draft-{level.lower()}-{typ}-{stamp}", "title": f"JLPT {level} {typ} drafts",
        "license": "CC BY-SA 4.0", "attribution": "Tsumugi contributors (LLM-drafted, unreviewed)",
        "passages": [], "items": items,
    }


# --- CLI ----------------------------------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="rule-based items from the built content packs")
    g.add_argument("--packs", type=Path, default=DEFAULT_PACKS)
    g.add_argument("--out", type=Path, default=HERE / "bank" / "jlpt_generated.json")
    g.add_argument("--per-type", type=int, default=80, help="items per type per level (default 80)")
    v = sub.add_parser("validate", help="check bank files and print the coverage table")
    v.add_argument("files", nargs="+", type=Path)
    v.add_argument("--packs", type=Path, default=DEFAULT_PACKS, help="for the vocabulary-within-level check")
    v.add_argument("--show-warnings", type=int, default=20, help="how many warnings to print (default 20)")
    v.add_argument("--strict-coverage", action="store_true", help="fail when a level lacks a full mock")
    d = sub.add_parser("draft", help="draft items through an OpenAI-compatible endpoint (source=llm)")
    d.add_argument("--endpoint", required=True, help="e.g. http://localhost:11434/v1 (Ollama)")
    d.add_argument("--model", required=True)
    d.add_argument("--level", required=True, choices=LEVELS)
    d.add_argument("--type", required=True, dest="typ")
    d.add_argument("--count", type=int, default=10)
    d.add_argument("--api-key-env", default="TSUMUGI_LLM_API_KEY", help="env var holding an optional API key")
    d.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    blueprint = load_blueprint()

    if args.cmd == "generate":
        report = generate(args.packs, args.out, args.per_type, blueprint)
        for level, types in report.items():
            for t, n in types.items():
                if n < 60:
                    print(f"note: {level} {t} reached {n} (< 60)", file=sys.stderr)
        return 0

    if args.cmd == "validate":
        form_level = None
        dict_pack = args.packs / "dictionary.sqlite"
        if dict_pack.exists():
            form_level = load_form_level(dict_pack)
        else:
            print(f"(no {dict_pack}: skipping the vocabulary-within-level check)")
        lattice = None
        if form_level is not None and (args.packs / "tokenizer.sqlite").exists():
            from lattice import Lattice

            lattice = Lattice(args.packs / "tokenizer.sqlite")
        rep = validate_banks(load_banks(args.files), blueprint, form_level, lattice)
        table, short = coverage_table(rep, blueprint)
        print("Coverage (items / needed for one full mock):")
        print(table)
        if short:
            print(f"\n{len(short)} level×type cells short of one full mock:")
            for s in short:
                print(f"  {s}")
        if form_level is not None:
            total = sum(rep.counts.values())
            flagged = sum(rep.vocab_warnings.values())
            how = "dictionary forms via the tokenizer" if lattice else "longest match"
            print(f"\nVocabulary above level: {flagged}/{total} items flagged ({how}, JMdict JLPT tags)")
        for w in rep.warnings[:args.show_warnings]:
            print(f"  warning: {w}")
        if len(rep.warnings) > args.show_warnings:
            print(f"  … {len(rep.warnings) - args.show_warnings} more warnings")
        for e in rep.errors:
            print(f"ERROR: {e}")
        print(f"\n{sum(rep.counts.values())} JLPT items, {len(rep.errors)} errors, {len(rep.warnings)} warnings")
        if rep.errors or (args.strict_coverage and short):
            return 1
        return 0

    if args.cmd == "draft":
        import os

        bank = draft(args.endpoint, args.model, args.level, args.typ, args.count, os.environ.get(args.api_key_env),
                     blueprint)
        rep = validate_banks([("draft", bank)], blueprint)
        for e in rep.errors:
            print(f"ERROR: {e}", file=sys.stderr)
        args.out.parent.mkdir(parents=True, exist_ok=True)
        write_bank(args.out, bank)
        print(f"wrote {len(bank['items'])} drafted items to {args.out} ({len(rep.errors)} validation errors; "
              f"fix them, then review with items/review.py)")
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
