@dataclass
class Word:
    id: int
    level: int
    rank: int
    kanji: list[str]
    kana: list[str]
    readings_for: dict[str, list[str]]  # kanji form -> hiragana readings
    pos: list[str]  # JMdict pos tags of the first sense
    uk: bool
    glosses: list[str]
    kana_raw: list[str] = field(default_factory=list)  # as written in JMdict (katakana kept), for display

    @property
    def written(self) -> str:
        return (self.kana_raw or self.kana)[0] if (self.uk or not self.kanji) else self.kanji[0]


BAD_KANJI_TAGS = {"rK", "iK", "oK", "sK", "ateji", "ik", "io"}
BAD_POS = {"n-pr", "ctr", "num", "pn", "pref", "suf", "n-suf", "exp", "int", "conj", "prt", "aux", "aux-v",
           "aux-adj", "cop", "unc"}


def coarse_pos(tags: list[str]) -> str:
    t = set(tags)
    if any(x.startswith("v5") or x in {"v1", "vk", "vs-i", "vs-s", "vz"} for x in t):
        return "verb"
    if "adj-i" in t or "adj-ix" in t:
        return "adj-i"
    if "adj-na" in t:
        return "adj-na"
    if "adv" in t and not ({"n", "n-adv"} & t):
        return "adv"
    if "n" in t or "vs" in t:
        return "noun"
    return "other"


class Packs:
    def __init__(self, packs: Path):
        self.dir = packs
        self.dict = sqlite3.connect(f"file:{packs / 'dictionary.sqlite'}?mode=ro", uri=True)
        g = packs / "grammar.sqlite"
        self.grammar = sqlite3.connect(f"file:{g}?mode=ro", uri=True) if g.exists() else None
        self._readings: dict[str, set[str]] = {}
        self._kanji: dict[str, tuple[int | None, list[str], list[str]]] = {}
        self.words: dict[int, Word] = {}
        self._load_words()
        self.sentences: dict[int, tuple[str, str, int | None]] = {
            sid: (ja, en, lv) for sid, ja, en, lv in self.dict.execute("SELECT id, ja, en, jlpt FROM sentence")
        }
        self.word_sentences: dict[int, list[int]] = defaultdict(list)
        for eid, sid in self.dict.execute("SELECT entry_id, sentence_id FROM sentence_word ORDER BY entry_id, sentence_id"):
            if eid in self.words:
                self.word_sentences[eid].append(sid)
        self.corpus = "\n" + "\n".join(ja for ja, _, _ in self.sentences.values()) + "\n"
        self._lattice = None
        self.stems: set[tuple] = set()

    def claim_stem(self, typ: str, stem: str, choices: list[str]) -> bool:
        """Register a stem bank-wide; False if it is already used (same rule as the validator)."""
        key = stem_key(typ, "", stem, "", choices)
        if key in self.stems:
            return False
        self.stems.add(key)
        return True

    @property
    def lattice(self):
        if self._lattice is None:
            from lattice import Lattice

            self._lattice = Lattice(self.dir / "tokenizer.sqlite")
        return self._lattice

    def _load_words(self) -> None:
        rows = self.dict.execute("SELECT id, jlpt, rank FROM entry WHERE jlpt IS NOT NULL ORDER BY rank, id").fetchall()
        ids = [r[0] for r in rows]
        kanji, kana, senses = defaultdict(list), defaultdict(list), {}
        for chunk in (ids[i:i + 900] for i in range(0, len(ids), 900)):
            q = ",".join("?" * len(chunk))
            for eid, text, tags in self.dict.execute(
                f"SELECT entry_id, text, tags FROM entry_kanji WHERE entry_id IN ({q}) ORDER BY entry_id, ord", chunk
            ):
                if not (set(json.loads(tags or "[]")) & BAD_KANJI_TAGS):
                    kanji[eid].append(text)
            for eid, text, tags, applies in self.dict.execute(
                f"SELECT entry_id, text, tags, applies_to FROM entry_kana WHERE entry_id IN ({q}) ORDER BY entry_id, ord",
                chunk,
            ):
                if not (set(json.loads(tags or "[]")) & BAD_KANJI_TAGS):
                    kana[eid].append((hira(text), json.loads(applies) if applies else ["*"], text))
            for eid, pos, glosses, misc in self.dict.execute(
                f"SELECT entry_id, pos, glosses, misc FROM sense WHERE entry_id IN ({q}) AND ord = 0", chunk
            ):
                senses[eid] = (json.loads(pos or "[]"), json.loads(glosses or "[]"), json.loads(misc or "[]"))
        for eid, jlpt, rank in rows:
            if eid not in senses or not kana[eid]:
                continue
            pos, glosses, misc = senses[eid]
            rf = {k: [r for r, ap, _ in kana[eid] if "*" in ap or k in ap] for k in kanji[eid]}
            self.words[eid] = Word(eid, jlpt, rank, kanji[eid], [r for r, _, _ in kana[eid]], rf, pos,
                                   "uk" in misc, glosses, [t for _, _, t in kana[eid]])

    def readings_of(self, written: str) -> set[str]:
        """Every hiragana reading JMdict gives the written form (all entries, not only JLPT-tagged ones)."""
        if written not in self._readings:
            out = set()
            for eid, in self.dict.execute("SELECT DISTINCT entry_id FROM entry_kanji WHERE text = ?", (written,)):
                for text, applies in self.dict.execute(
                    "SELECT text, applies_to FROM entry_kana WHERE entry_id = ?", (eid,)
                ):
                    ap = json.loads(applies) if applies else ["*"]
                    if "*" in ap or written in ap:
                        out.add(hira(text))
            self._readings[written] = out
        return self._readings[written]

    def word_readings(self) -> set[str]:
        if not hasattr(self, "_word_readings"):
            self._word_readings = {r for w in self.words.values() for r in w.kana}
        return self._word_readings

    def kanji_info(self, k: str) -> tuple[int | None, list[str], list[str]]:
        """(jlpt_new, on readings in hiragana, kun stems in hiragana)."""
        if k not in self._kanji:
            row = self.dict.execute("SELECT jlpt_new, onyomi, kunyomi FROM kanji WHERE literal = ?", (k,)).fetchone()
            if row is None:
                self._kanji[k] = (None, [], [])
            else:
                on = [hira(x) for x in json.loads(row[1] or "[]")]
                kun = sorted({x.split(".")[0].strip("-") for x in json.loads(row[2] or "[]")} - {""})
                self._kanji[k] = (row[0], on, kun)
        return self._kanji[k]

    def furigana(self, text: str, reading: str) -> list[tuple[str, str]] | None:
        row = self.dict.execute("SELECT segments FROM furigana WHERE text = ? AND reading = ?", (text, reading)).fetchone()
        if not row:
            return None
        segs = []
        for part in row[0].split("|"):
            ruby, _, rt = part.partition("=")
            segs.append((ruby, rt or ruby))
        return segs

    def kanji_by_reading(self) -> dict[str, list[str]]:
        if not hasattr(self, "_by_reading"):
            idx: dict[str, list[str]] = defaultdict(list)
            for lit, jl, on, kun in self.dict.execute(
                "SELECT literal, jlpt_new, onyomi, kunyomi FROM kanji WHERE jlpt_new IS NOT NULL ORDER BY freq, literal"
            ):
                rs = {hira(x) for x in json.loads(on or "[]")}
                rs |= {x.split(".")[0].strip("-") for x in json.loads(kun or "[]")}
                for r in rs - {""}:
                    idx[r].append(lit)
            self._by_reading = idx
        return self._by_reading

    def components(self, k: str) -> set[str]:
        return {r for r, in self.dict.execute("SELECT radical FROM kanji_component WHERE kanji = ?", (k,))}

    def lookalikes(self, k: str) -> list[str]:
        """JLPT-list kanji sharing a distinctive component with k (components in > 120 JLPT kanji, like 口 or
        一, don't count), most shared first."""
        if not hasattr(self, "_comp_index"):
            idx: dict[str, list[str]] = defaultdict(list)
            for kanji, rad in self.dict.execute(
                "SELECT c.kanji, c.radical FROM kanji_component c JOIN kanji k ON k.literal = c.kanji "
                "WHERE k.jlpt_new IS NOT NULL ORDER BY k.freq, c.kanji"
            ):
                idx[rad].append(kanji)
            self._comp_index = {r: ks for r, ks in idx.items() if len(ks) <= 120}
        score: Counter = Counter()
        for rad in self.components(k):
            for other in self._comp_index.get(rad, []):
                if other != k:
                    score[other] += 1
        return [o for o, _ in sorted(score.items(), key=lambda x: (-x[1], x[0]))]

    def attested(self, left: str, d: str, right: str = "") -> bool:
        """True if Tatoeba has `left + d + right` (a sign that d fits the slot)."""
        return (left + d + right) in self.corpus


