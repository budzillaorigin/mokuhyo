def item(iid: str, level: str, typ: str, stem: str, choices: list[str], answer: int, expl: str,
         refs: list[str], source: str = "generated") -> dict:
    return {
        "id": iid, "exam": "JLPT", "level": level, "type": typ, "stem": nfc(stem),
        "choices": [nfc(c) for c in choices], "answer": answer, "explanation": nfc(expl), "refs": refs,
        "source": source, "verified": False,
    }


def generate(packs: Path, out: Path, per_type: int, blueprint: dict[str, dict[str, int]]) -> dict:
    t0 = time.time()
    p = Packs(packs)
    pts = load_grammar(p)
    items: list[dict] = []
    report: dict[str, dict[str, int]] = {}
    for level in LEVELS:
        allowed = blueprint.get(level, {})
        used_vocab: set[int] = set()
        used_words: set[int] = set()
        used_grammar: set[int] = set()
        rep = report.setdefault(level, {})
        for typ in GENERATED_TYPES:
            if typ not in allowed:
                continue
            if typ in {"kanji_reading", "orthography"}:
                got = gen_kanji_items(p, level, per_type, used_vocab, used_words, typ)
            elif typ == "context":
                got = gen_context(p, level, per_type, used_vocab, used_words)
            elif typ == "grammar_form":
                got = gen_grammar_form(p, pts, level, per_type, used_grammar)
            else:
                got = gen_assembly(p, pts, level, per_type, used_grammar)
            rep[typ] = len(got)
            items += got
            print(f"{level} {typ}: {len(got)}", file=sys.stderr, flush=True)
    bank = dict(GENERATED_BANK)
    bank["passages"] = []
    bank["items"] = items
    out.parent.mkdir(parents=True, exist_ok=True)
    write_bank(out, bank)
    print(f"wrote {len(items)} items to {out} ({out.stat().st_size / 1e6:.2f} MB) in {time.time() - t0:.0f}s",
          file=sys.stderr)
    return report


def write_bank(path: Path, bank: dict) -> None:
    """One item/passage per line: stable diffs, reviewable, and compact."""
    lines = ["{"]
    for k in ("bank", "title", "license", "attribution"):
        lines.append(f"  {json.dumps(k)}: {json.dumps(bank[k], ensure_ascii=False)},")
    for k in ("passages", "items"):
        rows = bank.get(k, [])
        lines.append(f"  {json.dumps(k)}: [")
        for i, r in enumerate(rows):
            lines.append("    " + json.dumps(r, ensure_ascii=False) + ("," if i < len(rows) - 1 else ""))
        lines.append("  ]" + ("," if k == "passages" else ""))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


