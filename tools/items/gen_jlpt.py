@dataclass
class Span:
    start: int
    end: int
    surface: str
    reading: str  # hiragana
    head: object  # lattice Token of the content word
    tokens: list = field(default_factory=list)


AUX_OK = {"ます", "た", "ない", "たい", "だ", "ん", "う", "よう", "です", "まし", "でし", "なかっ", "ませ", "たかっ"}


def find_span(tokens, word: Word, sentence: str) -> Span | None:
    """Locate `word` in a tokenized sentence: the content token(s) plus trailing auxiliaries (ます, た, ない…).
    The tokenizer's reading must be a JMdict reading of the entry, which disambiguates homographs."""
    pos = coarse_pos(word.pos)
    forms = set(word.kanji) | set(word.kana) | set(word.kana_raw)
    for i, t in enumerate(tokens):
        j = None
        if pos in {"verb", "adj-i"}:
            if t.pos1 in {"動詞", "形容詞"} and t.base in forms:
                j = i + 1
        else:
            acc = ""
            for k in range(i, min(i + 4, len(tokens))):
                acc += tokens[k].surface
                if acc in forms:
                    j = k + 1
                    break
                if len(acc) >= max(map(len, forms)):
                    break
        if j is None:
            continue
        head = tokens[i:j]
        if any(not x.reading for x in head):
            return None
        # check the reading against the entry
        if pos in {"verb", "adj-i"}:
            parts = split_tail(t.surface, hira(t.reading))
            base_parts = None
            if t.base in word.kanji:
                # dictionary-form reading = core reading + base okurigana
                if parts:
                    base_parts = parts[1], parts[2]
                    base_tail = t.base[len(parts[0]) + len(parts[1]):]
                    if not t.base.startswith(parts[0] + parts[1]):
                        return None
                    dict_r = parts[2] + base_tail
                    if hira(parts[0]) + dict_r not in word.readings_for.get(t.base, []):
                        return None
            elif t.base not in word.kana and t.base not in word.kana_raw:
                return None
            del base_parts
        else:
            r = hira("".join(x.reading for x in head))
            surf = "".join(x.surface for x in head)
            ok = r in word.kana if (surf in word.kana or surf in word.kana_raw) else r in word.readings_for.get(surf, [])
            if not ok:
                return None
        # trailing auxiliaries
        while pos in {"verb", "adj-i"} and j < len(tokens) and (
            (tokens[j].pos1 == "助動詞" and tokens[j].surface in AUX_OK)
            or (tokens[j].pos1 == "動詞" and tokens[j].pos2 == "接尾")  # passive/causative れる・せる
            or (tokens[j].pos1 == "名詞" and tokens[j].pos2 == "接尾" and tokens[j].surface in {"さ", "み"})
            or (tokens[j].pos1 == "助詞" and tokens[j].pos2 == "接続助詞" and tokens[j].surface in {"て", "で", "ば"})
        ):
            j += 1
            if tokens[j - 1].pos1 == "助詞":
                break
        if tokens[j - 1].conj_form.startswith(("未然", "ガル")):
            return None  # the underline would end mid-word
        toks = tokens[i:j]
        surface = "".join(x.surface for x in toks)
        if sentence.count(surface) != 1:
            return None
        return Span(toks[0].start, toks[-1].end, surface, hira("".join(x.reading for x in toks)), t, toks)
    return None


def usable_sentences(p: Packs, word: Word, level: int, used: set[int], max_len: int = 36) -> list[int]:
    """Sentences whose every tagged word is at `level` or easier (`level` may be lowered by one in a relaxed
    second pass; the validator then flags the harder word)."""
    out = []
    for sid in p.word_sentences.get(word.id, []):
        ja, _, lv = p.sentences[sid]
        if sid in used or lv is None or lv < level or not (8 <= len(ja) <= max_len):
            continue
        if any(c in ja for c in "<>＿（）()「」『』"):
            continue
        out.append(sid)
    return sorted(out, key=lambda s: (len(p.sentences[s][0]), s))


def kanji_ok(p: Packs, written: str, level: int) -> bool:
    """Every kanji is on a JLPT kanji list at most one level above (the community N5 list has only ~80 kanji,
    fewer than the N5 vocabulary uses; N1 accepts any kanji)."""
    for c in written:
        if is_kanji(c):
            jl = p.kanji_info(c)[0]
            if level > 1 and (jl is None or jl < level - 1):
                return False
    return True


def wrong_readings(p: Packs, head: str, core: str, core_r: str, tail: str, dict_written: str,
                   dict_tail: str, key: str) -> list[str]:
    """Up to 3 wrong readings of head+core+tail, preferring real readings of the same kanji."""
    valid = p.readings_of(dict_written) | p.readings_of(head + core + tail)
    base_head = hira(head)
    segs = p.furigana(core, core_r) if len(core) > 1 else [(core, core_r)]
    if not segs or "".join(r for _, r in segs) != core_r:
        segs = None
    from_kanji: list[str] = []
    if segs:
        for i, (ruby, rt) in enumerate(segs):
            if len(ruby) != 1 or not is_kanji(ruby):
                continue
            _, on, kun = p.kanji_info(ruby)
            # compounds and okurigana words: other on-readings (起きます→ききます); lone kanji: kun too (人→じん)
            alts = on if (len(segs) > 1 or tail) else on + kun
            for alt in alts:
                if alt and alt != rt:
                    from_kanji.append("".join(a if j != i else alt for j, (_, a) in enumerate(segs)))
    variants = reading_variants([r for _, r in segs] if segs else [core_r])
    rng = seeded(key)
    rng.shuffle(from_kanji)
    rng.shuffle(variants)
    shifts = vowel_shifts(core_r)
    rng.shuffle(shifts)
    shifts.sort(key=lambda x: x not in p.word_readings())  # real words look more plausible
    out: list[str] = []
    pools = [from_kanji, variants]
    turn = 0
    while len(out) < 3 and (any(pools) or shifts):
        if any(pools):
            pool = pools[turn % 2] if pools[turn % 2] else pools[(turn + 1) % 2]
            turn += 1
        else:
            pool = shifts
        cand = pool.pop(0)
        full = base_head + cand + hira(tail)
        if abs(len(cand) - len(core_r)) > 2 or (len(core_r) >= 2 and len(cand) < 2):
            continue
        if cand == core_r or full in out or base_head + cand + dict_tail in valid or full in valid:
            continue
        if not all(is_hira(c) for c in cand) or re.search(r"[んっ][っんゃゅょぁぃぅぇぉ]", full):
            continue
        out.append(full)
    return out


def wrong_spellings(p: Packs, head: str, core: str, core_r: str, tail: str, dict_tail: str,
                    dict_reading: str, level: int, key: str) -> list[str]:
    """Up to 3 wrong written forms: one kanji swapped for a same-reading or look-alike kanji."""
    segs = p.furigana(core, core_r) if len(core) > 1 else [(core, core_r)]
    if not segs or "".join(r for _, r in segs) != core_r:
        return []
    by_r = p.kanji_by_reading()
    cands: list[tuple[int, str]] = []
    for i, (ruby, rt) in enumerate(segs):
        if len(ruby) != 1 or not is_kanji(ruby):
            continue
        comps = p.components(ruby)
        homophones = set(by_r.get(rt, []))
        pool = set(homophones) | set(p.lookalikes(ruby)[:12])
        # rendaku / sokuon variants of the segment reading still sound "the same" to a learner
        if rt and rt[0] in UNVOICE:
            homophones |= set(by_r.get(UNVOICE[rt[0]] + rt[1:], []))
        if rt.endswith("っ"):
            homophones |= set(by_r.get(rt[:-1] + "つ", [])) | set(by_r.get(rt[:-1] + "く", []))
        pool |= homophones
        for k in sorted(pool):
            if k == ruby:
                continue
            jl = p.kanji_info(k)[0]
            if jl is None or jl < max(level - 1, 1):
                continue
            score = 2 * len(comps & p.components(k)) + (3 if k in homophones else 0) + (1 if jl == p.kanji_info(ruby)[0] else 0)
            new = "".join(r if j != i else k for j, (r, _) in enumerate(segs))
            cands.append((-score, new))
    rng = seeded(key)
    rng.shuffle(cands)
    cands.sort(key=lambda x: x[0])
    out: list[str] = []
    for _, new in cands:
        full = head + new + tail
        if full in out or dict_reading in p.readings_of(head + new + dict_tail):
            continue
        out.append(full)
        if len(out) == 3:
            break
    return out


def answer_slot(key: str, index: int, n: int = 4) -> int:
    """Balanced, deterministic key positions: each block of n consecutive items uses every position once, in a
    seeded order."""
    perm = list(range(n))
    seeded(f"{key}/block{index // n}").shuffle(perm)
    return perm[index % n]


def stem_key(typ: str, passage_id: str, stem: str, script: str, choices: list[str]) -> tuple:
    """Duplicate-stem key. ★ stems are mostly slots (彼は　＿＿＿…), so their chunks are part of the key."""
    extra = tuple(sorted(choices)) if typ == "sentence_assembly" else ()
    return (typ, passage_id, stem, script, extra)


def place(correct: str, wrong: list[str], key: str, slot: int) -> tuple[list[str], int]:
    others = list(wrong)
    seeded(key + "/order").shuffle(others)
    choices = others[:slot] + [correct] + others[slot:]
    return choices, slot


def gloss(w: Word) -> str:
    return "; ".join(w.glosses[:3])


def passes(lv: int) -> list[int]:
    """Sentence-level floors: strict (all words at the level or easier), then one level harder."""
    return list(dict.fromkeys([lv, max(lv - 1, 1)]))


def gen_kanji_items(p: Packs, level: str, target: int, used: set[int], used_words: set[int], kind: str) -> list[dict]:
    """kind: kanji_reading | orthography. `used` (sentence ids) and `used_words` are shared by the level's
    vocabulary types so one mock never shows the same sentence or word twice."""
    lv = level_num(level)
    items: list[dict] = []
    abbr = "kr" if kind == "kanji_reading" else "or"
    words = sorted(p.words.values(), key=lambda w: (w.rank, w.id))
    for floor, w in ((f, w) for f in passes(lv) for w in words):
        if len(items) >= target:
            break
        if w.id in used_words:
            continue
        if w.level != lv or w.uk or not w.kanji or coarse_pos(w.pos) == "other" or set(w.pos) & BAD_POS:
            continue
        written = w.kanji[0]
        if not has_kanji(written) or not kanji_ok(p, written, lv):
            continue
        for sid in usable_sentences(p, w, floor, used):
            ja, en, _ = p.sentences[sid]
            span = find_span(p.lattice.tokenize(ja), w, ja)
            if not span or not has_kanji(span.surface):
                continue
            parts = split_tail(span.surface, span.reading)
            if not parts:
                continue
            head, core, core_r, tail = parts
            if not written.startswith(head + core):
                continue
            dict_tail = hira(written[len(head) + len(core):])
            dict_reading = hira(head) + core_r + dict_tail
            if dict_reading not in w.readings_for.get(written, []):
                continue
            key = f"{level}/{kind}/{w.id}/{sid}"
            if kind == "kanji_reading":
                wrong = wrong_readings(p, head, core, core_r, tail, written, dict_tail, key)
                correct = span.reading
                stem = ja[:span.start] + U_OPEN + span.surface + U_CLOSE + ja[span.end:]
                expl = (f"{span.surface} is read {span.reading} here ({written} 【{dict_reading}】: {gloss(w)}). "
                        f"JMdict gives no reading {', '.join(wrong)} for {written}. Sentence: “{en}”")
            else:
                wrong = wrong_spellings(p, head, core, core_r, tail, written[len(head) + len(core):],
                                        dict_reading, lv, key)
                correct = span.surface
                stem = ja[:span.start] + U_OPEN + span.reading + U_CLOSE + ja[span.end:]
                expl = (f"{span.reading} is written {span.surface} ({written}: {gloss(w)}). "
                        f"The other choices swap in a kanji with a similar reading or shape; none is a JMdict "
                        f"spelling of {dict_reading}. Sentence: “{en}”")
            if len(wrong) < 3 or len(set(wrong + [correct])) < 4 or not p.claim_stem(kind, stem, []):
                continue
            choices, answer = place(correct, wrong, key, answer_slot(f"{level}/{kind}", len(items)))
            used.add(sid)
            used_words.add(w.id)
            items.append(item(f"jlg-{level.lower()}-{abbr}-{len(items) + 1:04d}", level, kind, stem, choices,
                              answer, expl, [f"v:{w.id}", f"t:{sid}"]))
            break
    return items


# --- context (文脈規定) ---------------------------------------------------------------------------------------

STOP = {"to", "a", "an", "the", "of", "be", "one's", "oneself", "someone", "something", "etc.", "(", ")", "in",
        "on", "at", "for", "with", "and", "or", "as", "by", "up", "out", "from", "into", "about", "is", "it"}


def gloss_words(w: Word) -> set[str]:
    out = set()
    for g in w.glosses:
        for x in re.findall(r"[a-z][a-z'-]+", re.sub(r"\([^)]*\)", "", g.lower())):
            if x not in STOP:
                out.add(x)
    return out


COLLOC_PARTICLES = {"を", "が", "に", "で", "と"}
GENERIC_PREDICATES = {"ある", "いる", "する", "なる", "見る", "言う", "ない", "いい", "よい", "良い", "好き", "嫌い",
                      "欲しい", "思う", "できる", "出来る", "くれる", "もらう", "あげる", "やる", "持つ", "行く",
                      "来る", "使う", "買う", "見せる", "探す", "待つ", "話す", "聞く", "知る", "わかる", "分かる"}
TE_TA = {"た", "だ", "て", "で", "たら", "だら", "たり", "だり", "ても", "でも"}


def inflect_like(p: Packs, span: Span, base: str) -> str | None:
    """Inflect `base` like the span's head token, keeping the trailing auxiliaries (voicing た/て to だ/で after
    godan ガ/ナ/バ/マ-row verbs)."""
    head = span.tokens[0]
    rest = span.tokens[1:]
    if not head.conj_form:
        return base + "".join(t.surface for t in rest)
    forms = p.lattice.forms_of(base)
    if not forms:
        return None
    te_ta = bool(rest) and rest[0].surface in TE_TA
    if te_ta and head.conj_form in {"連用タ接続", "連用形"}:
        prefs = ["連用タ接続", "連用形"]
    else:
        prefs = [head.conj_form]
    for want in prefs:
        # prefer standard forms over the dialectal ウ音便 rows (吸うて) that ipadic also lists
        hits = sorted(("ウ音便" in ct, ct, min(lst)[0]) for (ct, cf), lst in forms.items() if cf == want)
        if hits:
            _, ctype, surface = hits[0]
            break
    else:
        return None
    tail = "".join(t.surface for t in rest)
    if te_ta:
        voiced = ctype.startswith(("五段・ガ行", "五段・ナ行", "五段・バ行", "五段・マ行"))
        first = rest[0].surface
        plain = {"だ": "た", "で": "て", "だら": "たら", "だり": "たり", "でも": "ても"}.get(first, first)
        swap = {"た": "だ", "て": "で", "たら": "だら", "たり": "だり", "ても": "でも"}
        tail = (swap[plain] if voiced else plain) + tail[len(first):]
    return surface + tail


def slot_class(head) -> str | None:
    """Word class of the blanked slot, from the tokenizer (distractors must share it)."""
    if head.pos1 == "動詞" and head.pos2 == "自立":
        return "verb"
    if head.pos1 == "形容詞" and head.pos2 == "自立":
        return "adj-i"
    if head.pos1 == "副詞":
        return "adv"
    if head.pos1 == "名詞":
        if head.pos2 == "形容動詞語幹":
            return "adj-na"
        if head.pos2 in {"一般", "サ変接続"}:
            return "noun"
    return None


def gen_context(p: Packs, level: str, target: int, used: set[int], used_words: set[int]) -> list[dict]:
    lv = level_num(level)
    pool: dict[str, list[Word]] = defaultdict(list)
    for w in sorted(p.words.values(), key=lambda w: (w.rank, w.id)):
        if w.level == lv and not (set(w.pos) & BAD_POS) and coarse_pos(w.pos) != "other":
            pool[coarse_pos(w.pos)].append(w)
    items: list[dict] = []
    order = sorted((w for ws in pool.values() for w in ws), key=lambda w: (w.rank, w.id))
    for floor, w in ((f, w) for f in passes(lv) for w in order):
        if len(items) >= target:
            break
        if w.id in used_words:
            continue
        pos = coarse_pos(w.pos)
        trans = {"vt", "vi"} & set(w.pos)
        mine = gloss_words(w)
        for sid in usable_sentences(p, w, floor, used, max_len=40):
            ja, en, _ = p.sentences[sid]
            if len(ja) < 10:
                continue
            toks = p.lattice.tokenize(ja)
            span = find_span(toks, w, ja)
            if not span or slot_class(span.head) != pos:
                continue
            # neighbours: the nearest content word on the left (+ particles), and the next token on the right
            idx = next(i for i, t in enumerate(toks) if t.start == span.start)
            left, k = "", idx - 1
            while k >= 0 and toks[k].pos1 == "助詞" and len(left) < 3:
                left = toks[k].surface + left
                k -= 1
            has_left_word = k >= 0 and toks[k].pos1 in {"名詞", "動詞", "形容詞", "副詞"}
            if has_left_word:
                left = toks[k].surface + left
            j = next(i for i, t in enumerate(toks) if t.end == span.end) + 1
            right = toks[j].surface if j < len(toks) and toks[j].pos1 != "記号" else ""
            if not has_left_word and not (right and toks[j].pos1 in {"名詞", "動詞", "形容詞"}):
                continue  # too little context to rule the distractors out
            colloc = ""
            if pos in {"noun", "adj-na"}:
                # nouns fit almost any slot (彼は（　　）が好き); only use a noun whose slot is fixed by a
                # collocation: particle + a non-generic predicate, attested at least twice with this noun.
                if not (j + 1 < len(toks) and toks[j].pos1 == "助詞" and toks[j].surface in COLLOC_PARTICLES
                        and toks[j + 1].pos1 in {"動詞", "形容詞"} and toks[j + 1].pos2 == "自立"
                        and toks[j + 1].base not in GENERIC_PREDICATES):
                    continue
                colloc = toks[j].surface + toks[j + 1].base[:-1]
                if p.corpus.count(span.surface + colloc) < 2:
                    continue
            elif not has_left_word:
                continue
            elif pos == "adv":
                # the adverb must collocate with what follows (attested elsewhere in Tatoeba)
                if not right or p.corpus.count(span.surface + right) < 2:
                    continue
            elif p.corpus.count(left + span.head.surface) < 2 or toks[k].pos2 == "代名詞":
                continue  # verbs/adjectives: the left neighbour must be a real collocate (not 彼が（　　）)
            suru = "vs" in w.pos and j < len(toks) and toks[j].base == "する"
            key = f"{level}/context/{w.id}/{sid}"
            cands = [d for d in pool[pos] if d.id != w.id]
            seeded(key).shuffle(cands)
            wrong: list[str] = []
            for d in cands:
                if trans and pos == "verb" and not (trans & set(d.pos)):
                    continue
                if suru and "vs" not in d.pos:
                    continue
                if gloss_words(d) & mine:
                    continue
                base = d.written
                if pos in {"verb", "adj-i"}:
                    surf = inflect_like(p, span, base)
                    stem = base[:-1]
                else:
                    surf = base + "".join(t.surface for t in span.tokens[1:])
                    stem = base
                if not surf or surf == span.surface or surf in wrong or surf in ja or not stem:
                    continue
                if left and p.attested(left, stem):
                    continue
                if right and p.attested(surf, right):
                    continue
                if len(stem) == 1 and left and p.attested(left[-1:], stem):
                    continue
                if colloc and p.attested(stem, colloc):
                    continue
                wrong.append(surf)
                if len(wrong) == 3:
                    break
            if len(wrong) < 3:
                continue
            stem_text = ja[:span.start] + BLANK + ja[span.end:]
            if not p.claim_stem("context", stem_text, []):
                continue
            choices, answer = place(span.surface, wrong, key, answer_slot(f"{level}/context", len(items)))
            used.add(sid)
            used_words.add(w.id)
            expl = (f"“{en}” Only {span.surface} ({w.written}: {gloss(w)}) fits. The others are {level} words of "
                    f"the same part of speech that do not fit this context.")
            items.append(item(f"jlg-{level.lower()}-cx-{len(items) + 1:04d}", level, "context", stem_text, choices,
                              answer, expl, [f"v:{w.id}", f"t:{sid}"]))
            break
    return items


# --- grammar ------------------------------------------------------------------------------------------------


def utf16_to_py(s: str, off: int) -> int:
    n = 0
    for i, c in enumerate(s):
        if n >= off:
            return i
        n += 2 if ord(c) > 0xFFFF else 1
    return len(s)


@dataclass
class GPoint:
    id: str
    level: int
    title: str
    meaning: str
    related: list[str]
    patterns: list[re.Pattern]
    examples: list[tuple[int, str, str, int, int, int | None, str]]  # ord, ja, en, start, end, tatoeba id, source


def load_grammar(p: Packs) -> dict[str, GPoint]:
    if p.grammar is None:
        return {}
    pts: dict[str, GPoint] = {}
    for pid, jlpt, title, meaning, related in p.grammar.execute(
        "SELECT id, jlpt, title, meaning, related FROM grammar_point ORDER BY jlpt DESC, ord"
    ):
        pts[pid] = GPoint(pid, jlpt, title, meaning, json.loads(related or "[]"), [], [])
    for pid, rx in p.grammar.execute("SELECT point_id, regex FROM grammar_pattern ORDER BY point_id, ord"):
        if pid in pts:
            try:
                pts[pid].patterns.append(re.compile(rx))
            except re.error:
                pass
    for pid, o, ja, en, bs, be, src, tid in p.grammar.execute(
        "SELECT point_id, ord, ja, en, blank_start, blank_end, source, tatoeba_id FROM grammar_example "
        "ORDER BY point_id, ord"
    ):
        if pid in pts:
            s, e = utf16_to_py(ja, bs), utf16_to_py(ja, be)
            if 0 <= s < e <= len(ja):
                pts[pid].examples.append((o, ja, en, s, e, tid, src))
    return pts


def meaning_words(m: str) -> set[str]:
    return {x for x in re.findall(r"[a-z][a-z'-]+", re.sub(r"\([^)]*\)", "", m.lower()))} - STOP


FUNCTION_AUX = {"だ", "です", "ます", "た", "ない", "う", "ん", "ぬ"}


def blank_ok(p: Packs, ja: str, s: int, e: int) -> bool:
    """A usable grammar blank: it starts and ends on token boundaries, contains kana and no digits/Latin, and is
    more than a bare particle or a copula/ます/た ending (those have too many acceptable alternatives for a
    rule-built item to be unambiguous: 私（は／も）…, 学生（です／でした）)."""
    text = ja[s:e]
    if not any(is_hira(c) for c in text) or re.search(r"[0-9０-９A-Za-zＡ-Ｚａ-ｚ]", text):
        return False
    toks = p.lattice.tokenize(ja)
    starts = {t.start for t in toks}
    ends = {t.end for t in toks}
    if s not in starts or e not in ends:
        return False
    inner = [t for t in toks if s <= t.start and t.end <= e]
    if not inner or all(t.pos1 in {"助詞", "記号"} for t in inner):
        return False
    if all(t.pos1 in {"助動詞", "記号"} and t.base in FUNCTION_AUX | {"。"} for t in inner):
        return False
    # a grammar form, not a lexical choice (給料を（あげる／もらう）): at least one function word
    if not any(t.pos1 in {"助詞", "助動詞"} or t.pos2 in {"非自立", "接尾"} for t in inner):
        return False
    # must not end mid-word (もらっ｜た, てくれませ｜ん)
    after = [t for t in toks if t.start == e]
    continues = bool(after) and (after[0].pos1 == "助動詞" or (
        after[0].pos1 == "助詞" and after[0].pos2 == "接続助詞" and after[0].surface in {"て", "で", "ば"}))
    return not (continues or inner[-1].surface.endswith("っ")
                or inner[-1].conj_form.startswith(("未然", "連用タ接続")))


def connection(p: Packs, ja: str, s: int) -> str:
    """What the blank attaches to: part of speech (+ conjugated form) of the token before it."""
    prev = [t for t in p.lattice.tokenize(ja) if t.end == s]
    if not prev:
        return "BOS"
    t = prev[0]
    return f"{t.pos1}/{t.conj_form}" if t.conj_form else f"{t.pos1}/{t.pos2}"


def gen_grammar_form(p: Packs, pts: dict[str, GPoint], level: str, target: int, used: set[int]) -> list[dict]:
    """Distractors come from examples of other points whose blank attaches to a different kind of word (after a
    noun vs after a て-form…), so each is wrong by connection, not merely by nuance: rule-built items cannot
    judge nuance, and a distractor that is also grammatical would make the key ambiguous."""
    lv = level_num(level)
    here = [g for g in pts.values() if g.level == lv]
    clean: dict[str, list[tuple[str, str]]] = {}
    for g in pts.values():
        if g.level != lv and not any(g.id in h.related for h in here):
            continue
        opts = set()
        for _, ja, _, s, e, _, _ in g.examples:
            if blank_ok(p, ja, s, e):
                opts.add((ja[s:e], connection(p, ja, s)))
        clean[g.id] = sorted(opts)
    blanks: dict[str, set[str]] = {g.id: {ja[s:e] for _, ja, _, s, e, _, _ in g.examples} for g in pts.values()}
    items: list[dict] = []
    # round-robin over points so every point gets items before any point gets a second one
    rounds = max((len(g.examples) for g in here), default=0)
    for r in range(rounds):
        for g in here:
            if len(items) >= target:
                return items
            exs = [x for x in g.examples if x[6] == "tatoeba" and x[5] not in used]
            if r >= len(exs):
                continue
            _, ja, en, s, e, tid, _ = exs[r]
            ans = ja[s:e]
            if s == 0 or len(ja) > 45 or BLANK in ja or ja.count(ans) != 1 or not blank_ok(p, ja, s, e):
                continue  # (a sentence-initial slot takes almost any adverbial)
            before = connection(p, ja, s)
            mine_conn = {c for _, c in clean.get(g.id, [])} | {before}
            key = f"{level}/grammar_form/{g.id}/{tid}"
            related = [pts[x] for x in g.related if x in pts]
            same = [x for x in here if x.id != g.id and x.id not in g.related]
            seeded(key).shuffle(same)
            mine = meaning_words(g.meaning)
            wrong: list[str] = []
            wrong_pts: list[GPoint] = []
            for other in related + same:
                if meaning_words(other.meaning) & mine:
                    continue
                opts = [o for o, c in clean.get(other.id, []) if c not in mine_conn]
                seeded(key + other.id).shuffle(opts)
                for d in opts:
                    if d == ans or d in blanks[g.id] or d in wrong or ans in d or d in ans:
                        continue
                    if d[:2] == ans[:2] or any(d[:2] == w[:2] for w in wrong):
                        continue  # same head (はずがない / はずだった): likely variants of each other
                    if abs(len(d) - len(ans)) > 4:
                        continue
                    filled = ja[:s] + d + ja[e:]
                    if any(rx.search(filled) for rx in g.patterns):
                        continue
                    if p.attested(ja[max(0, s - 2):s], d, ja[e:e + 1]):
                        continue
                    wrong.append(d)
                    wrong_pts.append(other)
                    break
                if len(wrong) == 3:
                    break
            if len(wrong) < 3 or not p.claim_stem("grammar_form", ja[:s] + BLANK + ja[e:], []):
                continue
            choices, answer = place(ans, wrong, key, answer_slot(f"{level}/grammar_form", len(items)))
            used.add(tid)
            others = "; ".join(f"{d} ({o.title}: {o.meaning})" for d, o in zip(wrong, wrong_pts))
            expl = (f"“{en}” {g.title}: {g.meaning}. The other choices are patterns that attach to a different kind "
                    f"of word, so they cannot follow {ja[max(0, s - 4):s] or 'the start'} here: {others}.")
            items.append(item(f"jlg-{level.lower()}-gf-{len(items) + 1:04d}", level, "grammar_form",
                              ja[:s] + BLANK + ja[e:], choices, answer, expl, [f"g:{g.id}", f"t:{tid}"]))
    return items


INDEPENDENT = {"名詞", "動詞", "形容詞", "副詞", "連体詞", "接続詞", "感動詞", "接頭詞"}
FREE_PARTICLES = {"が", "を", "に", "で", "へ", "と", "から", "まで", "は", "も", "より"}


def bunsetsu(tokens) -> list[list]:
    """Split tokens into bunsetsu: a content word (plus compound nouns, suffixes, prefixes) followed by its
    function words. 名詞・非自立 (こと, の, よう, ため…) starts its own chunk, which suits ★ items."""
    chunks: list[list] = []
    for i, t in enumerate(tokens):
        prev = tokens[i - 1] if i else None
        starts = t.pos1 in INDEPENDENT
        if t.pos1 == "名詞" and t.pos2 in {"接尾"}:
            starts = False
        if t.pos1 == "動詞" and t.pos2 in {"非自立", "接尾"}:
            starts = False
        if t.pos1 == "形容詞" and t.pos2 == "非自立":
            starts = False
        if prev is not None and prev.pos1 == "接頭詞":
            starts = False
        if (t.pos1 == "名詞" and prev is not None and prev.pos1 == "名詞" and t.pos2 != "非自立"
                and prev.pos2 != "非自立"):
            starts = False
        if t.pos1 == "動詞" and t.base == "する" and prev is not None and prev.pos2 == "サ変接続":
            starts = False  # 勉強する stays one chunk
        if t.pos1 == "形容詞" and prev is not None and prev.pos1 == "名詞" and prev.pos2 == "一般":
            starts = False  # 礼儀正しい, 気持ちいい
        if t.pos1 == "記号" and t.surface in "「『（":
            starts = True
        if starts or not chunks:
            chunks.append([t])
        else:
            chunks[-1].append(t)
    return chunks


def is_free_chunk(ch) -> bool:
    """Chunks that can usually be moved around a clause without breaking it: an argument ending in a case/topic
    particle (本を, そこへ, 方へ, nominalized 言いつけで), a bare adverb, or an adverbial noun (昨日, 毎朝).
    A ★ window with two of these often has two correct orders, so it is rejected."""
    if len(ch) == 1 and (ch[0].pos1 == "副詞" or (ch[0].pos1 == "名詞" and ch[0].pos2 == "副詞可能")):
        return True
    last = ch[-1]
    if last.pos1 != "助詞" or last.surface not in FREE_PARTICLES or len(ch) < 2:
        return False
    body = ch[:-1]
    if any(t.pos1 == "助動詞" for t in body):
        return False
    verbs = [t for t in body if t.pos1 in {"動詞", "形容詞"}]
    return not verbs or (len(verbs) == 1 and body[-1] is verbs[0] and verbs[0].conj_form == "連用形")


def gen_assembly(p: Packs, pts: dict[str, GPoint], level: str, target: int, used: set[int]) -> list[dict]:
    lv = level_num(level)
    here = [g for g in pts.values() if g.level == lv]
    items: list[dict] = []
    rounds = max((len(g.examples) for g in here), default=0)
    for r in range(rounds):
        for g in here:
            if len(items) >= target:
                return items
            exs = [x for x in g.examples if x[6] == "tatoeba" and x[5] not in used]
            if r >= len(exs):
                continue
            _, ja, en, s, e, tid, _ = exs[r]
            if not (12 <= len(ja) <= 45):
                continue
            chunks = bunsetsu(p.lattice.tokenize(ja))
            # chunk spans without trailing punctuation (it stays in the stem)
            spans = []
            for c in chunks:
                core = [t for t in c if t.pos1 != "記号"] or c
                spans.append((c[0].start, core[-1].end))
            texts_all = [ja[a0:b0] for a0, b0 in spans]
            best = None
            for a in range(1, len(chunks) - 3):  # a >= 1: some text before the slots
                win = list(range(a, a + 4))
                if any(all(t.pos1 == "記号" for t in chunks[i]) for i in win):
                    continue
                if any(chunks[i][-1].pos1 == "記号" and i != win[-1] for i in win):
                    continue  # punctuation inside the window
                ws, we = spans[a][0], spans[a + 3][1]
                if we <= s or ws >= e:
                    continue  # must include part of the grammar construction
                texts = [texts_all[i] for i in win]
                if len(set(texts)) < 4 or any(len(x) > 12 or not x for x in texts):
                    continue
                if sum(is_free_chunk(chunks[i]) for i in win) > 1:
                    continue
                ends = [chunks[i][-1].surface for i in win if chunks[i][-1].pos1 == "助詞"]
                if len(ends) != len(set(ends)):
                    continue
                best = (a, texts, ws, we)
                break
            if best is None:
                continue
            a, texts, ws, we = best
            key = f"{level}/sentence_assembly/{g.id}/{tid}"
            stem = ja[:ws] + f"\u3000{SLOT}\u3000{SLOT}\u3000{STAR}\u3000{SLOT}"
            rest = ja[we:]
            stem += ("\u3000" + rest if rest and not all(c in "。！？!?" for c in rest) else rest)
            correct = texts[2]
            if not p.claim_stem("sentence_assembly", stem, texts):
                continue
            choices, answer = place(correct, texts[:2] + texts[3:], key,
                                    answer_slot(f"{level}/sentence_assembly", len(items)))
            expl = (f"Correct order: {' / '.join(texts)} → {ja} (“{en}”). ★ is {correct}. "
                    f"Grammar point: {g.title} ({g.meaning}).")
            used.add(tid)
            items.append(item(f"jlg-{level.lower()}-sa-{len(items) + 1:04d}", level, "sentence_assembly", stem,
                              choices, answer, expl, [f"g:{g.id}", f"t:{tid}"]))
    return items


